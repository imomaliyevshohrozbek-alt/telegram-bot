def make_keyboard(options, answered=False, correct=None, chosen=None):
    buttons = []
    for i, opt in enumerate(options):
        prefix = ""
        if answered:
            if i == correct:
                prefix = "✅ "
            elif i == chosen:
                prefix = "❌ "
        buttons.append([InlineKeyboardButton(
            f"{LETTERS[i]}. {prefix}{opt}",
            callback_data=f"ans_{i}"
        )])
    return InlineKeyboardMarkup(buttons)

